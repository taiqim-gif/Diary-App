/* =========================================================
   予想気温の推定(日の出・日の入の時刻)
   気象庁の予報には、時刻ごとの気温がないので、最低・最高から推定する
   ・日の出 ≒ その日の最低気温(一日で一番冷えるのは、日の出のころ)
   ・日の入 = 最低 + (最高 − 最低) × sin(π × 昼の長さ ÷ (昼の長さ + 3.72時間))
     (Parton と Logan の気温の日変化のモデル。最高気温は昼過ぎに来る)
========================================================= */
function estTemps(min, max, riseMin, setMin){
  const out = { rise:null, set:null };
  if(min != null && isFinite(min)) out.rise = Math.round(min);
  if(min != null && max != null && isFinite(min) && isFinite(max) && riseMin != null && setMin != null && max >= min){
    const dl = (setMin - riseMin) / 60;
    out.set = Math.round(min + (max - min) * Math.sin(Math.PI * dl / (dl + 2 * 1.86)));
  }
  return out;
}

