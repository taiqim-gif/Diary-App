  const D = 297.8501921 + 445267.1114034 * T, M = 357.5291092 + 35999.0502909 * T;
  const Mm = 134.9633964 + 477198.8675055 * T, F = 93.2720950 + 483202.0175233 * T;
  const s = x => Math.sin(x * RAD);
  const moon = 218.3164477 + 481267.88123421 * T
    + 6.288774 * s(Mm) + 1.274027 * s(2 * D - Mm) + 0.658314 * s(2 * D) + 0.213618 * s(2 * Mm) - 0.185116 * s(M) - 0.114332 * s(2 * F)
    + 0.058793 * s(2 * D - 2 * Mm) + 0.057066 * s(2 * D - M - Mm) + 0.053322 * s(2 * D + Mm) + 0.045758 * s(2 * D - M)
    - 0.040923 * s(M - Mm) - 0.034720 * s(D) - 0.030383 * s(M + Mm);
  const L0 = 280.46646 + 36000.76983 * T;
  const sunL = L0 + (1.914602 - 0.004817 * T) * s(M) + 0.019993 * s(2 * M) + 0.000289 * s(3 * M);
