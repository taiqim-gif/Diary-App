/* =========================================================
   日の出・日の入(NOAA の計算式。誤差は1分ほど)
   戻り値: その日の0時(日本時間)からの分。出ない・沈まないときは null
========================================================= */
function sunEvent(key, lat, lng, rise){
  const p = keyParts(key), jd0 = Date.UTC(p[0], p[1] - 1, p[2]) / DAY + 2440587.5;
  let t = 720;                                             // 正午から始めて、2回計算し直して近づける
  for(let i = 0; i < 2; i++){
    const T = (jd0 + (t - 540) / 1440 - 2451545) / 36525;  // 日本時間 → 世界時(9時間引く)
    const L0 = (280.46646 + T * (36000.76983 + T * 0.0003032)) % 360;
    const M = 357.52911 + T * (35999.05029 - 0.0001537 * T);
    const e = 0.016708634 - T * (0.000042037 + 0.0000001267 * T);
    const C = Math.sin(M * RAD) * (1.914602 - T * (0.004817 + 0.000014 * T)) + Math.sin(2 * M * RAD) * (0.019993 - 0.000101 * T) + Math.sin(3 * M * RAD) * 0.000289;
    const om = 125.04 - 1934.136 * T;
    const lam = L0 + C - 0.00569 - 0.00478 * Math.sin(om * RAD);
    const eps0 = 23 + (26 + (21.448 - T * (46.815 + T * (0.00059 - T * 0.001813))) / 60) / 60;
    const eps = eps0 + 0.00256 * Math.cos(om * RAD);
    const decl = Math.asin(Math.sin(eps * RAD) * Math.sin(lam * RAD));
    const y = Math.pow(Math.tan(eps * RAD / 2), 2);
    const eot = 4 / RAD * (y * Math.sin(2 * L0 * RAD) - 2 * e * Math.sin(M * RAD) + 4 * e * y * Math.sin(M * RAD) * Math.cos(2 * L0 * RAD)
      - 0.5 * y * y * Math.sin(4 * L0 * RAD) - 1.25 * e * e * Math.sin(2 * M * RAD));      // 均時差(分)
    const cosH = (Math.cos(90.833 * RAD) - Math.sin(lat * RAD) * Math.sin(decl)) / (Math.cos(lat * RAD) * Math.cos(decl));
    if(cosH > 1 || cosH < -1) return null;
    const H = Math.acos(cosH) / RAD;
    const noon = 720 - 4 * lng - eot + 540;               // 南中の時刻(日本時間)
    t = rise ? noon - 4 * H : noon + 4 * H;
  }
  return t;
}
