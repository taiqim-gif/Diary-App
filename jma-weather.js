const codeWord = code => { const c = String(code || ""); return CODE_WORDS[c] || ({ "1":"晴れ", "2":"くもり", "3":"雨", "4":"雪" })[c[0]] || ""; };
const codeIcon = code => ({ "1":"☀", "2":"☁", "3":"☂", "4":"❄" })[String(code || "")[0]] || "";
function iconsFromText(text, code){                            // 言葉に出てくる順に、最大2つ(晴れ のち くもり → ☀☁)
  const out = [], re = /晴|くもり|曇|雨|雪|雷/g, map = { "晴":"☀", "くもり":"☁", "曇":"☁", "雨":"☂", "雪":"❄", "雷":"⚡" };
  let m;
  while((m = re.exec(String(text || "")))){ const ic = map[m[0]]; if(out[out.length - 1] !== ic) out.push(ic); }
  return out.length ? out.slice(0, 2).join("") : codeIcon(code);
}
// 今日・明日・明後日の3日分(日の出・日の入・月も入れる)
function days(d, nowMs){
  return ["今日", "明日", "明後日"].map((label, i) => {
    const key = jstKey(nowMs + i * DAY), out = { label, key, disp: monthDay(key) };
    const si = (d.wTimes || []).findIndex(t => String(t).slice(0, 10) === key);
    const wi = (d.wkT || []).findIndex(t => String(t).slice(0, 10) === key);
    if(si >= 0 && d.weathers && d.weathers[si]){ out.text = d.weathers[si]; out.code = (d.codes || [])[si]; out.word = out.text.split(" ")[0]; }
    else if(wi >= 0 && d.wkCodes && d.wkCodes[wi]){ out.code = d.wkCodes[wi]; out.text = codeWord(out.code); out.word = out.text.replace(/ /g, ""); }
    const tm = Object.assign({}, (d.memo || {})[key] || {}, tempsByDay(d)[key] || {});
    if(i === 0 && d.memo && d.memo[key] && d.memo[key].min != null) tm.min = d.memo[key].min;
    if(tm.max == null && wi >= 0 && d.wkMax){ const v = parseFloat(d.wkMax[wi]); if(isFinite(v)) tm.max = v; }
    if(tm.min == null && wi >= 0 && d.wkMin){ const v = parseFloat(d.wkMin[wi]); if(isFinite(v)) tm.min = v; }
    out.max = tm.max; out.min = tm.min;
    if(i === 0) out.popsNow = pops6(d, nowMs);
    else{
      const vals = [];
      (d.popsT || []).forEach((t, j) => { if(String(t).slice(0, 10) === key){ const v = parseFloat(d.popsV[j]); if(isFinite(v)) vals.push(v); } });
      if(vals.length) out.pop = Math.max(...vals);
      else if(wi >= 0 && d.wkPops){ const v = parseFloat(d.wkPops[wi]); if(isFinite(v)) out.pop = v; }
    }
    if(d.point){                                               // 日の出・日の入は、気温の地点の位置で計算する
      const s = sun(key, d.point.lat, d.point.lng), et = estTemps(out.min, out.max, s.rise, s.set);
      out.rise = s.rise; out.set = s.set; out.riseTemp = et.rise; out.setTemp = et.set;
    }
    out.moon = moon(noonMs(key));                              // 月齢は、その日の正午(暦と同じ決まり)
    return out;
  });
}
// 気温の色: 0℃未満=紫、0℃=濃い青、1〜9℃=水色、10〜19℃=緑、20〜24℃=だいだい、25℃以上=赤
function tempColor(n){
  if(n < 0) return "#7B3FC4";
  if(n < 1) return "#1F55C4";
  if(n < 10) return "#2A9FD6";
  if(n < 20) return "#2E9E5B";
  if(n < 25) return "#E8890C";
  return "#D62E2E";
}

